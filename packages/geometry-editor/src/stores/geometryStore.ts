// Generate default coordinates for any element type
export const generateDefaultCoordinates = (element: Element): Array<{x: number, y: number, z: number}> => {
  switch (element.type) {
    case 'BuildingElementOpaque':
    case 'BuildingElementTransparent':
      return generateWallCoordinates(
        element.width || 1.0,
        element.height || PROJECT_DEFAULTS.wall_height,
        element.orientation360 || 0,
        0, // Default to origin
        0  // Default to origin
      );
    case 'BuildingElementGround':
      return generateGroundCoordinates(
        element.area,
        element.perimeter
      );
    case 'BuildingElementAdjacentConditionedSpace':
    case 'BuildingElementAdjacentUnconditionedSpace_Simple':
    case 'BuildingElementPartyWall':
      // Adjacent elements behave like linear segments in plan but may lack orientation fields.
      // Provide a simple visible 1m east-facing default at origin. UI can later project to a parent wall.
      return generateWallCoordinates(1.0, element.height || PROJECT_DEFAULTS.wall_height, 90, 0, 0);
    case 'WetEmitter':
      try {
        const se = element as any;
        if (se.subcategory === 'ufh') {
          // Small rectangle polygon to visualize UFH by default
          return [
            { x: 0, y: 0, z: PROJECT_DEFAULTS.base_z },
            { x: 2, y: 0, z: PROJECT_DEFAULTS.base_z },
            { x: 2, y: 1, z: PROJECT_DEFAULTS.base_z },
            { x: 0, y: 1, z: PROJECT_DEFAULTS.base_z },
          ];
        }
      } catch { /* swallow: best-effort */ }
      // Default for radiator/fancoil: short 1m segment at origin
      return generateWallCoordinates(1.0, 0.5, 0, 0, 0);
    case 'WindowShading':
    case 'MechanicalVentilationTerminal':
      // Place as a single point by default at origin (z from project default base)
      return [
        { x: 0, y: 0, z: PROJECT_DEFAULTS.base_z }
      ];
    case 'ContextShading':
      // Default to a small polygon so it renders as a shaded area
      return [
        { x: -0.5, y: -0.5, z: PROJECT_DEFAULTS.base_z },
        { x: 0.5, y: -0.5, z: PROJECT_DEFAULTS.base_z },
        { x: 0.5, y: 0.5, z: PROJECT_DEFAULTS.base_z },
        { x: -0.5, y: 0.5, z: PROJECT_DEFAULTS.base_z }
      ];
    default:
      // Fallback to default wall coordinates
      return generateWallCoordinates(1.0, PROJECT_DEFAULTS.wall_height, 0, 0, 0);
  }
};

// Derivation Functions - Calculate properties from coordinates
export const deriveWallProperties = (
  element: Element,
  globalOrientationOffset: number,
): {
  width: number;
  height: number;
  orientation360: number;
  area: number;
  perimeter: number;
  center_x: number;
  center_y: number;
} => {
  const coordinates = element.coordinates;
  const height = ('height' in element) ? element.height || PROJECT_DEFAULTS.wall_height : PROJECT_DEFAULTS.wall_height;

  if (coordinates.length !== 2) {
    throw new Error('Wall must have exactly 2 coordinates');
  }

  const [A, B] = coordinates;
  const dx = B.x - A.x;
  const dy = B.y - A.y;

  // Width = distance between points A and B
  const width = Math.sqrt(dx * dx + dy * dy);

  // Handle degenerate segments
  let orientation360 = ('orientation360' in element) ? element.orientation360 || 0 : 0; // Keep prior orientation
  if (width >= PROJECT_DEFAULTS.min_segment) {
    // Calculate orientation360 from the outward-facing normal implied by
    // the directed segment A→B, then apply the global north offset using
    // the same subtractive convention as the rest of the model.
    const outwardOrientation360 = orientation360FromSegmentOutwardModelXY(A.x, A.y, B.x, B.y, 0);
    orientation360 = normalizeOrientation360Deg((outwardOrientation360 ?? orientation360) - globalOrientationOffset);
    // Round to 2 decimal places for data quality and ECaaS compatibility
    orientation360 = roundToTwoDecimals(orientation360);

  } else {
    // Emit GEO-007 warning for degenerate segment
    console.warn(`GEO-007: Near-zero segment ${width.toFixed(3)}m < ${PROJECT_DEFAULTS.min_segment}m`);
  }

  // Area = width × height (height is scalar)
  // Round to 2 decimal places for consistency (was 3dp, but 2dp is sufficient and matches ECaaS requirements)
  const area = roundToTwoDecimals(width * height);

  // Perimeter = 2 × (width + height)
  const perimeter = roundToTwoDecimals(2 * (width + height));

  // Center = midpoint of segment AB
  const center_x = roundToTwoDecimals((A.x + B.x) / 2);
  const center_y = roundToTwoDecimals((A.y + B.y) / 2);

  return {
    width: roundToTwoDecimals(width),
    height: roundToTwoDecimals(height),
    orientation360,
    area,
    perimeter,
    center_x,
    center_y
  };
};

// NOTE: strictest numeric typing coercion lives in `lib/schemaCoercion.ts`

export const deriveGroundProperties = (element: Element): {
  area: number;
  perimeter: number;
  total_area: number;
} => {
  const coordinates = element.coordinates;
  if (coordinates.length < 2) {
    throw new Error('Ground must have at least 2 coordinates');
  }

  const extra = (element as any).extra_json && typeof (element as any).extra_json === 'object' && !Array.isArray((element as any).extra_json)
    ? ((element as any).extra_json as Record<string, unknown>)
    : {};

  if (coordinates.length === 2) {
    const [a, b] = coordinates;
    const length = Math.hypot(b.x - a.x, b.y - a.y);
    const lineHeight = typeof extra._ground_line_height_m === 'number' && Number.isFinite(extra._ground_line_height_m)
      ? Math.max(0, extra._ground_line_height_m)
      : 0;
    const lineArea = length * lineHeight;
    return {
      area: roundToTwoDecimals(lineArea),
      perimeter: roundToTwoDecimals(length),
      total_area: roundToTwoDecimals(lineArea),
    };
  }

  const footprintArea = calculatePolygonArea(coordinates);
  const perimeter = calculatePolygonPerimeter(coordinates);

  return {
    area: roundToTwoDecimals(footprintArea),
    perimeter: roundToTwoDecimals(perimeter),
    total_area: roundToTwoDecimals(footprintArea) // Footprint area for global/zone floor metrics
  };
};

// Helper functions for polygon calculations
// calculatePolygonArea is now imported from polygonSync

const calculatePolygonPerimeter = (coordinates: Array<{x: number, y: number, z: number}>): number => {
  let perimeter = 0;
  for (let i = 0; i < coordinates.length; i++) {
    const current = coordinates[i];
    const next = coordinates[(i + 1) % coordinates.length];
    perimeter += Math.sqrt(
      Math.pow(next.x - current.x, 2) +
      Math.pow(next.y - current.y, 2)
    );
  }
  return roundToTwoDecimals(perimeter);
};

