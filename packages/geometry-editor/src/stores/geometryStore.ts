function removeParentControlledFloorMoveDerivedFields(
  prevElement: Element,
  normalizedUpdates: Partial<Element>,
): void {
  delete (normalizedUpdates as Record<string, unknown>).base_height;
  delete (normalizedUpdates as Record<string, unknown>)._base_height;
  delete (normalizedUpdates as Record<string, unknown>).mid_height;

  if (
    prevElement.type !== 'BuildingElementTransparent' ||
    !Object.prototype.hasOwnProperty.call(normalizedUpdates, 'extra_json')
  ) {
    return;
  }

  const nextExtra = readJsonRecord((normalizedUpdates as { extra_json?: unknown }).extra_json);
  if (!nextExtra || !Object.prototype.hasOwnProperty.call(nextExtra, 'window_part_list')) return;
  const previousExtra = readJsonRecord(prevElement.extra_json);
  const restoredExtra = { ...nextExtra };
  if (previousExtra && Object.prototype.hasOwnProperty.call(previousExtra, 'window_part_list')) {
    restoredExtra.window_part_list = previousExtra.window_part_list;
  } else {
    delete restoredExtra.window_part_list;
  }
  (normalizedUpdates as { extra_json?: unknown }).extra_json = restoredExtra;
}

function enforceParentControlledFloorOnUpdate(
  prevElement: Element,
  normalizedUpdates: Partial<Element>,
  elementsById: Record<string, Element>,
  floors: Floor[],
  ensureFloorForZ: (zIndex: number) => string,
): boolean {
  const draft = { ...prevElement, ...normalizedUpdates } as Element;
  const parent = getFloorControlParentElement(draft, elementsById);
  if (!parent) return false;
  const parentFloorZ = getElementCanvasFloorZValue(parent, floors);
  if (parentFloorZ === undefined) return false;

  const hasFloorIdUpdate = Object.prototype.hasOwnProperty.call(normalizedUpdates, 'floorId');
  const hasCoordinateUpdate = Object.prototype.hasOwnProperty.call(normalizedUpdates, 'coordinates');
  if (!hasFloorIdUpdate && !hasCoordinateUpdate) return false;

  const requestedFloorZ = hasCoordinateUpdate
    ? floorZFromCoordinates((normalizedUpdates as { coordinates?: unknown }).coordinates)
    : floorZFromFloorId((normalizedUpdates as { floorId?: unknown }).floorId, floors);
  const targetFloorZ = Math.floor(parentFloorZ);
  const floorMismatch = requestedFloorZ !== undefined && requestedFloorZ !== targetFloorZ;

  (normalizedUpdates as { floorId?: string }).floorId = ensureFloorForZ(targetFloorZ);
  if (!usesPhysicalZWithFloorMembership(draft) && !preservesCoordinateZForParentControlledFloor(draft)) {
    const sourceCoordinates =
      (Array.isArray((normalizedUpdates as { coordinates?: unknown }).coordinates)
        ? (normalizedUpdates as { coordinates?: ElementCoordinate[] }).coordinates
        : prevElement.coordinates) ?? [];
    if (sourceCoordinates.length > 0) {
      (normalizedUpdates as { coordinates?: ElementCoordinate[] }).coordinates = sourceCoordinates.map((coord) => ({
        ...coord,
        z: targetFloorZ,
      }));
    }
  }

  if (floorMismatch) {
    removeParentControlledFloorMoveDerivedFields(prevElement, normalizedUpdates);
  }

  return true;
}

const applyCoordinateDerivedElementFields = (
  element: Element,
  coordsChanged: boolean,
  globalOrientationOffset: number,
): void => {
  if (coordsChanged && isWallLikeLineElement(element)) {
    const d = deriveWallProperties(element, globalOrientationOffset);
    (element as any).width = d.width;
    (element as any).area = d.area;
    (element as any).perimeter = d.perimeter;
    (element as any).orientation360 = d.orientation360;
  } else if (coordsChanged && isSlopedFabricEnvelopePolygon(element)) {
    const o = deriveSlopedPolygonOrientation360(element, globalOrientationOffset);
    if (o !== null) {
      (element as any).orientation360 = o;
    }
  } else if (element.type === 'BuildingElementGround') {
    const d = deriveGroundProperties(element);
    (element as any).area = d.area;
    (element as any).total_area = d.total_area;
    const currentPerimeter = (element as { perimeter?: unknown }).perimeter;
    if (typeof currentPerimeter !== 'number' || !Number.isFinite(currentPerimeter)) {
      (element as any).perimeter = d.perimeter;
    }
  } else if (element.type === 'ThermalBridgeLinear') {
    const coords = element.coordinates;
    if (coords && coords.length === 2) {
      (element as any).length = syncThermalBridgeLinearLengthFromCoordinates(element as ThermalBridgeLinear);
    }
  } else if (element.type === 'WaterPipework' || element.type === 'MechanicalVentilationDuctwork') {
    const coords = element.coordinates;
    if (coords && coords.length === 2) {
      const [A, B] = coords;
      (element as any).length = roundToTwoDecimals(Math.hypot(B.x - A.x, B.y - A.y, B.z - A.z));
    }
  }

  Object.assign(element, syncPolygonElement(element, globalOrientationOffset));

  if (element.type === 'OnSiteGeneration' && coordsChanged) {
    if (!('pitch' in element) || (element as any).pitch === undefined || (element as any).pitch === null) {
      (element as any).pitch = 0;
    }
    if (!('orientation360' in element) || (element as any).orientation360 === undefined || (element as any).orientation360 === null) {
      (element as any).orientation360 = 0;
    }
  }
};

export type MirrorDirection = 'left-right' | 'top-bottom';

type PlanPointTransform = (point: { x: number; y: number }) => { x: number; y: number };

function cleanTransformedPlanNumber(value: number): number {
  const cleaned = Math.round(value * 1e10) / 1e10;
  return Object.is(cleaned, -0) ? 0 : cleaned;
}

function selectionPlanBoundsCenter(
  elementsById: Record<string, Element>,
  elementIds: string[],
): { x: number; y: number } | null {
  const xs: number[] = [];
  const ys: number[] = [];
  for (const id of elementIds) {
    const coordinates = elementsById[id]?.coordinates ?? [];
    for (const coordinate of coordinates) {
      if (!Number.isFinite(coordinate.x) || !Number.isFinite(coordinate.y)) continue;
      xs.push(coordinate.x);
      ys.push(coordinate.y);
    }
  }
  if (xs.length === 0) return null;
  return {
    x: (Math.min(...xs) + Math.max(...xs)) / 2,
    y: (Math.min(...ys) + Math.max(...ys)) / 2,
  };
}

function planTransformElementIds(
  elementsById: Record<string, Element>,
  selectedElementIds: string[],
): string[] {
  const ids = new Set(selectedElementIds.filter((id) => !!elementsById[id]));
  const queue = [...ids];
  const processed = new Set<string>();

  while (queue.length > 0) {
    const parentId = queue.shift();
    if (!parentId || processed.has(parentId)) continue;
    processed.add(parentId);

    for (const descendantId of collectHostedDescendantElementIds(elementsById, parentId)) {
      if (ids.has(descendantId)) continue;
      ids.add(descendantId);
      queue.push(descendantId);
    }

    const parentName = elementsById[parentId]?.name;
    if (!parentName) continue;
    for (const candidate of Object.values(elementsById)) {
      if (
        candidate.type !== 'MechanicalVentilationTerminal' ||
        candidate.host_element !== parentName ||
        ids.has(candidate.id)
      ) {
        continue;
      }
      ids.add(candidate.id);
      queue.push(candidate.id);
    }
  }

  return [...ids];
}

function mirroredCoordinateOrder(
  element: Element,
  coordinates: Element['coordinates'],
): Element['coordinates'] {
  const shape = getElementShape(element);
  if (shape === 'line') return [...coordinates].reverse();
  if ((shape === 'polygon' || shape === 'sloped-polygon') && coordinates.length >= 3) {
    return [coordinates[1], coordinates[0], ...coordinates.slice(2).reverse()];
  }
  return coordinates;
}

function transformDormerBundlePlanPoint(
  extraJson: Element['extra_json'],
  transformPoint: PlanPointTransform,
): Element['extra_json'] {
  if (!extraJson || typeof extraJson !== 'object' || Array.isArray(extraJson)) return extraJson;
  const bundle = extraJson.dormer_bundle;
  if (!bundle || typeof bundle !== 'object' || Array.isArray(bundle)) return extraJson;
  const parameters = (bundle as Record<string, unknown>).parameters;
  if (!parameters || typeof parameters !== 'object' || Array.isArray(parameters)) return extraJson;
  const point = (parameters as Record<string, unknown>).windowCenterPlanPoint;
  if (!point || typeof point !== 'object' || Array.isArray(point)) return extraJson;
  const x = (point as Record<string, unknown>).x;
  const y = (point as Record<string, unknown>).y;
  if (typeof x !== 'number' || typeof y !== 'number') return extraJson;
  const transformed = transformPoint({ x, y });
  return {
    ...extraJson,
    dormer_bundle: {
      ...(bundle as Record<string, unknown>),
      parameters: {
        ...(parameters as Record<string, unknown>),
        windowCenterPlanPoint: {
          ...(point as Record<string, unknown>),
          x: cleanTransformedPlanNumber(transformed.x),
          y: cleanTransformedPlanNumber(transformed.y),
        },
      },
    },
  };
}

function transformSelectedPlanGeometry(
  state: GeometryState,
  selectedElementIds: string[],
  transformPoint: PlanPointTransform,
  transformOrientation: (orientation360: number) => number,
  mirror: boolean,
): Record<string, Element> | null {
  const transformIds = planTransformElementIds(state.elementsById, selectedElementIds);
  if (transformIds.length === 0) return null;

  const updatedElementsById = { ...state.elementsById };
  let changed = false;
  for (const id of transformIds) {
    const element = state.elementsById[id];
    if (!element?.coordinates?.length) continue;
    let coordinates = element.coordinates.map((coordinate) => {
      const transformed = transformPoint(coordinate);
      return {
        ...coordinate,
        x: cleanTransformedPlanNumber(transformed.x),
        y: cleanTransformedPlanNumber(transformed.y),
      };
    });
    if (mirror) coordinates = mirroredCoordinateOrder(element, coordinates);

    const currentOrientation = (element as { orientation360?: unknown }).orientation360;
    const extraJson = transformDormerBundlePlanPoint(element.extra_json, transformPoint);
    const nextElement = {
      ...element,
      coordinates,
      ...(typeof currentOrientation === 'number' && Number.isFinite(currentOrientation)
        ? { orientation360: roundToTwoDecimals(transformOrientation(currentOrientation)) }
        : {}),
      ...(extraJson !== element.extra_json ? { extra_json: extraJson } : {}),
      _v: (element._v ?? 0) + 1,
    } as Element;
    applyCoordinateDerivedElementFields(nextElement, true, state.globalOrientationOffset);
    updatedElementsById[id] = nextElement;
    changed = true;
  }
  return changed ? updatedElementsById : null;
}

const applyAutoNameToElementDraft = (
  prevElement: Element,
  draftElement: Element,
  elementsById: Record<string, Element>,
  floors: Floor[],
  elementId: string,
  updateKeys: string[],
  globalOrientationOffset: number,
  namingPreferences: NamingPreferences,
  options: {
    coordsChanged: boolean;
    userExplicitlySetOrientation360: boolean;
    target: Partial<Element>;
    debugPhase: string;
  },
): void => {
  // Base names for line walls use orientation; when coordinates are updated without an explicit
  // orientation360 patch, derive from the new segment before computing the auto-name base.
  let namingForAuto: Pick<Element, 'type'> & Partial<Element> = draftElement;
  if (
    options.coordsChanged &&
    !options.userExplicitlySetOrientation360 &&
    isWallLikeLineElement(draftElement)
  ) {
    const d = deriveWallProperties(draftElement, globalOrientationOffset);
    namingForAuto = { ...(draftElement as any), orientation360: d.orientation360 } as Pick<Element, 'type'> & Partial<Element>;
  } else if (
    options.coordsChanged &&
    !options.userExplicitlySetOrientation360 &&
    isSlopedFabricEnvelopePolygon(draftElement as Element)
  ) {
    const o = deriveSlopedPolygonOrientation360(draftElement as Element, globalOrientationOffset);
    if (o !== null) {
      namingForAuto = { ...(draftElement as any), orientation360: o } as Pick<Element, 'type'> & Partial<Element>;
    }
  }

  const previousBaseName = getAutoElementBaseName(prevElement, elementsById, floors, undefined, namingPreferences, undefined, globalOrientationOffset);
  const nextBaseName = getAutoElementBaseName(namingForAuto, elementsById, floors, undefined, namingPreferences, undefined, globalOrientationOffset);
  const autoNameDriverChanged = previousBaseName !== nextBaseName;
  const canAuto = isNameAutoSyncEnabled(prevElement, elementsById, floors, namingPreferences, globalOrientationOffset);
  if (autoNameDriverChanged && canAuto) {
    (options.target as any).name = generateDefaultElementName(namingForAuto, elementsById, elementId, floors, namingPreferences, undefined, globalOrientationOffset);
    (options.target as any)._nameAutoSync = true;
  }

  if (getNameDebugConfig() && shouldNameDebugForElementId(elementId)) {
    const oPrev = (prevElement as { orientation360?: number }).orientation360;
    const oFromMerged = (draftElement as { orientation360?: number }).orientation360;
    const oForAuto = (namingForAuto as { orientation360?: number }).orientation360;
    logNameDebug(options.debugPhase, {
      elementId,
      type: prevElement.type,
      prevName: prevElement.name,
      prevNameAutoSync: (prevElement as { _nameAutoSync?: boolean })._nameAutoSync,
      isNameAutoSyncEnabled: canAuto,
      autoNameDriverChanged,
      previousBaseName,
      nextBaseName,
      willRename: autoNameDriverChanged && canAuto,
      updateKeys,
      orientation360: { prev: oPrev, mergedField: oFromMerged, forAutoName: oForAuto },
    });
  }
};

