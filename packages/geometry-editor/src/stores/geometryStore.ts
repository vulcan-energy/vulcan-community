/**
 * Convert scalar sloped-rooflight dimension edits into geometry before the element is written.
 * Explicit coordinates remain authoritative for canvas and generated-geometry updates.
 */
const applyTransparentOpeningSlopedDimensionGeometry = (
  prevElement: Element,
  normalizedUpdates: Partial<Element>,
  explicitCoordinatesProvided: boolean,
): void => {
  if (prevElement.type !== 'BuildingElementTransparent') return;
  const updateRecord = normalizedUpdates as Record<string, unknown>;
  const widthUpdate = updateRecord.width;
  const heightUpdate = updateRecord.height;
  const widthProvided = typeof widthUpdate === 'number' && Number.isFinite(widthUpdate);
  const heightProvided = typeof heightUpdate === 'number' && Number.isFinite(heightUpdate);
  if ((!widthProvided && !heightProvided) || explicitCoordinatesProvided) return;

  const draft = { ...prevElement, ...normalizedUpdates } as BuildingElementTransparent;
  if (getElementShape(draft) !== 'sloped-polygon') return;
  const derived = deriveSlopedElementDimensions(draft);
  const nextWidth = widthProvided
    ? widthUpdate
    : typeof prevElement.width === 'number' && Number.isFinite(prevElement.width) && prevElement.width > 0
      ? prevElement.width
      : derived?.width;
  const nextHeight = heightProvided
    ? heightUpdate
    : typeof prevElement.height === 'number' && Number.isFinite(prevElement.height) && prevElement.height > 0
      ? prevElement.height
      : derived?.height;
  if (
    typeof nextWidth !== 'number' || !Number.isFinite(nextWidth) || nextWidth <= 0 ||
    typeof nextHeight !== 'number' || !Number.isFinite(nextHeight) || nextHeight <= 0
  ) return;

  const geometryPatch = buildSlopedPolygonRectangleDimensionPatch({
    coordinates: draft.coordinates,
    widthM: nextWidth,
    heightM: nextHeight,
    pitchDegrees: draft.pitch,
  });
  if (geometryPatch) Object.assign(updateRecord, geometryPatch);
};

/** Keep automatic opening fields aligned with the final geometry while preserving manual values. */
const applyTransparentOpeningAutomaticFields = (
  prevElement: Element,
  nextElement: Element,
  normalizedUpdates: Partial<Element>,
  effectiveFloors: Floor[],
): void => {
  if (
    prevElement.type !== 'BuildingElementTransparent' ||
    nextElement.type !== 'BuildingElementTransparent'
  ) return;
  const updateRecord = normalizedUpdates as Record<string, unknown>;
  const hasInvalidDriver = TRANSPARENT_OPENING_DERIVATION_DRIVERS.some(
    (field) => Object.prototype.hasOwnProperty.call(updateRecord, field) &&
      (typeof updateRecord[field] !== 'number' || !Number.isFinite(updateRecord[field])),
  );
  if (hasInvalidDriver) return;

  const directNumericPatch: TransparentOpeningNumericPatch = {};
  const previousRecord = prevElement as unknown as Record<string, unknown>;
  const nextRecord = nextElement as unknown as Record<string, unknown>;
  for (const field of TRANSPARENT_OPENING_DERIVATION_DRIVERS) {
    const previousValue = previousRecord[field];
    const nextValue = nextRecord[field];
    if (
      typeof nextValue === 'number' &&
      Number.isFinite(nextValue) &&
      (
        Object.prototype.hasOwnProperty.call(updateRecord, field) ||
        previousValue !== nextValue
      )
    ) {
      directNumericPatch[field] = nextValue;
    }
  }
  if (Object.keys(directNumericPatch).length === 0) return;
  if (Object.prototype.hasOwnProperty.call(updateRecord, 'mid_height')) {
    const explicitMidHeight = updateRecord.mid_height;
    if (typeof explicitMidHeight === 'number' && Number.isFinite(explicitMidHeight)) {
      directNumericPatch.mid_height = explicitMidHeight;
    }
  }
  if (Object.prototype.hasOwnProperty.call(updateRecord, 'max_window_open_area')) {
    const explicitMaxOpenArea = updateRecord.max_window_open_area;
    if (typeof explicitMaxOpenArea === 'number' && Number.isFinite(explicitMaxOpenArea)) {
      directNumericPatch.max_window_open_area = explicitMaxOpenArea;
    }
  }

  const canonicalPatch = buildTransparentOpeningNumericPatch(
    prevElement,
    directNumericPatch,
    { effectiveFloors },
  );
  if (
    !Object.prototype.hasOwnProperty.call(updateRecord, 'mid_height') &&
    typeof canonicalPatch.mid_height === 'number'
  ) {
    nextElement.mid_height = canonicalPatch.mid_height;
  }
  if (
    !Object.prototype.hasOwnProperty.call(updateRecord, 'max_window_open_area') &&
    typeof canonicalPatch.max_window_open_area === 'number'
  ) {
    nextElement.max_window_open_area = canonicalPatch.max_window_open_area;
  }
};

