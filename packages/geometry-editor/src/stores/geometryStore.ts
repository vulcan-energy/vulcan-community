const projectPointToSegment = (
  point: ElementCoordinate,
  segment: [ElementCoordinate, ElementCoordinate],
): ElementCoordinate => {
  const [a, b] = segment;
  const vx = b.x - a.x;
  const vy = b.y - a.y;
  const v2 = vx * vx + vy * vy || 1;
  const t = Math.max(0, Math.min(1, ((point.x - a.x) * vx + (point.y - a.y) * vy) / v2));
  return {
    x: a.x + t * vx,
    y: a.y + t * vy,
    z: point.z ?? a.z,
  };
};

const midpointOnSegment = (segment: [ElementCoordinate, ElementCoordinate], z?: number): ElementCoordinate => {
  const [a, b] = segment;
  return {
    x: (a.x + b.x) / 2,
    y: (a.y + b.y) / 2,
    z: z ?? ((a.z + b.z) / 2),
  };
};

const getWindowLineCoordinates = (
  windowElement: BuildingElementTransparent | undefined,
): [ElementCoordinate, ElementCoordinate] | null => {
  if (!windowElement || !Array.isArray(windowElement.coordinates) || windowElement.coordinates.length < 2) {
    return null;
  }
  const [a, b] = windowElement.coordinates;
  if (!a || !b) return null;
  return [a, b] as [ElementCoordinate, ElementCoordinate];
};

const segmentFractionForPoint = (
  point: ElementCoordinate,
  segment: [ElementCoordinate, ElementCoordinate],
): number => {
  const [a, b] = segment;
  const vx = b.x - a.x;
  const vy = b.y - a.y;
  const v2 = vx * vx + vy * vy || 1;
  return Math.max(0, Math.min(1, ((point.x - a.x) * vx + (point.y - a.y) * vy) / v2));
};

const pointAtSegmentFraction = (
  segment: [ElementCoordinate, ElementCoordinate],
  fraction: number,
): ElementCoordinate => {
  const [a, b] = segment;
  const t = Math.max(0, Math.min(1, fraction));
  return {
    x: a.x + (b.x - a.x) * t,
    y: a.y + (b.y - a.y) * t,
    z: a.z + ((b.z ?? a.z) - a.z) * t,
  };
};

const copyWindowShadingCoordinates = (
  shading: WindowShading,
  sourceWindow: BuildingElementTransparent,
  targetWindow: BuildingElementTransparent,
): ElementCoordinate[] => {
  const targetSegment = getWindowLineCoordinates(targetWindow);
  if (!targetSegment) {
    return Array.isArray(targetWindow.coordinates) && targetWindow.coordinates.length > 0
      ? [{ ...(targetWindow.coordinates[0] as ElementCoordinate) }]
      : (shading.coordinates ?? []).map((coordinate) => ({ ...coordinate }));
  }

  const sourceSegment = getWindowLineCoordinates(sourceWindow);
  const sourcePoint = shading.coordinates?.[0] as ElementCoordinate | undefined;
  if (!sourceSegment || !sourcePoint) {
    return [midpointOnSegment(targetSegment)];
  }

  return [pointAtSegmentFraction(targetSegment, segmentFractionForPoint(sourcePoint, sourceSegment))];
};

const cloneJsonValue = (value: unknown): unknown => {
  if (Array.isArray(value)) return value.map(cloneJsonValue);
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>).map(([key, child]) => [key, cloneJsonValue(child)]),
    );
  }
  return value;
};

const jsonValuesEqual = (a: unknown, b: unknown): boolean => {
  if (Object.is(a, b)) return true;
  if (Array.isArray(a) || Array.isArray(b)) {
    if (!Array.isArray(a) || !Array.isArray(b) || a.length !== b.length) return false;
    return a.every((item, index) => jsonValuesEqual(item, b[index]));
  }
  if (a && b && typeof a === 'object' && typeof b === 'object') {
    const aEntries = Object.entries(a as Record<string, unknown>);
    const bRecord = b as Record<string, unknown>;
    if (aEntries.length !== Object.keys(bRecord).length) return false;
    return aEntries.every(([key, value]) =>
      Object.prototype.hasOwnProperty.call(bRecord, key) && jsonValuesEqual(value, bRecord[key]),
    );
  }
  return false;
};

