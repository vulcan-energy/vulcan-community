const getOrientationSuffix = (
  element: Pick<Element, 'type'> & Partial<Element>,
  preferences: NamingPreferences,
  globalOrientationOffset: number,
): string => {
  let orientation: number | null = null;
  const orientationRaw = (element as { orientation360?: unknown }).orientation360;
  if (typeof orientationRaw === 'number' && Number.isFinite(orientationRaw)) {
    orientation = orientationRaw;
  } else if (Array.isArray(element.coordinates) && element.coordinates.length >= 3) {
    orientation = deriveSlopedPolygonOrientation360(element as Element, globalOrientationOffset);
  } else if (Array.isArray(element.coordinates) && element.coordinates.length === 2) {
    try {
      orientation = deriveWallProperties(element as Element, globalOrientationOffset).orientation360;
    } catch {
      orientation = null;
    }
  }
  if (orientation === null) return '';
  const normalized = normalizeOrientation360Deg(orientation);
  return formatOrientationLabel(normalized, preferences.orientationLabelStyle);
};

const inferHorizontalAdjacencySurface = (
  element: Pick<Element, 'type'> & Partial<Element>,
  elementsById: Record<string, Element>,
): 'floor' | 'ceiling' => {
  if (element.type === 'BuildingElementAdjacentConditionedSpace') return 'floor';
  const elementZ = getElementCanvasFloorZValue(element as Element);
  if (typeof elementZ !== 'number' || !Number.isFinite(elementZ)) return 'floor';

  const referenceWallZs = Object.values(elementsById)
    .filter((candidate) => {
      if (candidate.type !== 'BuildingElementOpaque') return false;
      if (element.zoneId && candidate.zoneId !== element.zoneId) return false;
      return classifyPitch(candidate.pitch) === 'vertical';
    })
    .map((candidate) => getElementCanvasFloorZValue(candidate))
    .filter((z): z is number => typeof z === 'number' && Number.isFinite(z));

  if (referenceWallZs.length === 0) return 'floor';
  const maxWallZ = Math.max(...referenceWallZs);
  return elementZ > maxWallZ + FLOOR_RELATION_EPSILON ? 'ceiling' : 'floor';
};

const getAdjacentSurfaceName = (
  element: Pick<Element, 'type'> & Partial<Element>,
  elementsById: Record<string, Element>,
): { suffix: string; useOrientation: boolean } => {
  const shape = getElementShape(element as Element);
  if (shape === 'line') return { suffix: 'Wall', useOrientation: true };
  const pitchClass = classifyPitch((element as { pitch?: unknown }).pitch);
  if (pitchClass === 'vertical') return { suffix: 'Wall', useOrientation: true };
  if (pitchClass === 'horizontal-up') return { suffix: 'Floor', useOrientation: false };
  if (pitchClass === 'horizontal-down') return { suffix: 'Ceiling', useOrientation: false };
  // Sloped adjacent/party/unheated planes are named as ceilings. External roof
  // naming still distinguishes pitched roofs on BuildingElementOpaque.
  if (pitchClass === 'up-facing-slope') return { suffix: 'Ceiling', useOrientation: true };
  if (pitchClass === 'down-facing-slope') return { suffix: 'Ceiling', useOrientation: true };
  return inferHorizontalAdjacencySurface(element, elementsById) === 'ceiling'
    ? { suffix: 'Ceiling', useOrientation: false }
    : { suffix: 'Floor', useOrientation: false };
};

