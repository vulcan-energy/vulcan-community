const getAutoElementBaseName = (
  element: Pick<Element, 'type'> & Partial<Element>,
  elementsById: Record<string, Element> = {},
  floors?: Floor[],
  number?: string,
  preferences: NamingPreferences = DEFAULT_NAMING_PREFERENCES_FOR_AUTO_SYNC,
  floorLabelForStorey?: (storeyIndex: number | undefined) => string,
  globalOrientationOffset = 0,
): string => {
  const format = (parts: Omit<ElementAutoNameParts, 'floor'>) => formatConfiguredAutoName(
    number ? { ...parts, number } : parts,
    element,
    floors,
    preferences,
    floorLabelForStorey,
  );

  if (element.type === 'System') {
    const typeLabelFromExtraJson = extractSystemTypeLabelFromExtraJson(element);
    if (typeLabelFromExtraJson) {
      return format(
        {
          ruleId: 'systemDerived',
          defaultLabel: typeLabelFromExtraJson,
          derivedLabel: typeLabelFromExtraJson,
          derivedOptionId: typeLabelFromExtraJson,
        }
      );
    }
    if (element.extra_json && typeof element.extra_json === 'object' && !Array.isArray(element.extra_json)) {
      const pcdb = (element.extra_json as Record<string, unknown>)._pcdb;
      if (pcdb && typeof pcdb === 'object' && !Array.isArray(pcdb)) {
        const productType = (pcdb as Record<string, unknown>).productType;
        if (typeof productType === 'string' && productType.trim()) {
          const normalizedType = normalizeAutoNameTypeToken(productType);
          if (normalizedType) {
            return format(
              {
                ruleId: 'systemDerived',
                defaultLabel: normalizedType,
                derivedLabel: normalizedType,
                derivedOptionId: normalizedType,
              }
            );
          }
        }
      }
    }
    const subcategory = element.subcategory as System['subcategory'] | undefined;
    const defaultLabel = subcategory ? (SYSTEM_SUBCATEGORY_AUTO_NAME_LABELS[subcategory] ?? 'System') : 'System';
    return format({ ruleId: 'systemDerived', defaultLabel, derivedLabel: defaultLabel, derivedOptionId: subcategory });
  }

  if (element.type === 'WetEmitter') {
    const subcategory = element.subcategory as WetEmitter['subcategory'] | undefined;
    let defaultLabel = getElementTypeBaseName(element.type);
    if (subcategory === 'ufh') defaultLabel = 'Underfloor Heating';
    if (subcategory === 'fancoil') defaultLabel = 'Fan Coil';
    if (subcategory === 'radiator') defaultLabel = 'Radiator';
    return format({ ruleId: 'wetEmitterDerived', defaultLabel, derivedLabel: defaultLabel, derivedOptionId: subcategory });
  }

  if (element.type === 'MechanicalVentilation') {
    const rawVentType = typeof element.vent_type === 'string' ? element.vent_type : '';
    const ventType = rawVentType ? normalizeAutoNameLabel(rawVentType) : '';
    const defaultLabel = ventType || 'Ventilation';
    return format({ ruleId: 'mechanicalVentilationDerived', defaultLabel, derivedLabel: defaultLabel, derivedOptionId: rawVentType || undefined });
  }

  if (element.type === 'BuildingElementOpaque') {
    if (element.is_external_door === true) {
      return format({ ruleId: 'externalDoor', defaultLabel: 'Door' });
    }
    const pitchClass = classifyPitch(element.pitch);
    if (pitchClass === 'vertical') {
      return format({ ruleId: 'externalWall', defaultLabel: 'Wall', orientation: getOrientationSuffix(element, preferences, globalOrientationOffset) });
    }
    if (pitchClass === 'horizontal-up') {
      return format({ ruleId: 'flatRoof', defaultLabel: 'Flat Roof' });
    }
    if (pitchClass === 'horizontal-down') {
      return format({ ruleId: 'exposedFloor', defaultLabel: 'Exposed Floor' });
    }
    if (pitchClass === 'up-facing-slope') {
      return format({ ruleId: 'pitchedRoof', defaultLabel: 'Pitched Roof', orientation: getOrientationSuffix(element, preferences, globalOrientationOffset) });
    }
    if (pitchClass === 'down-facing-slope') {
      return format({ ruleId: 'exposedFloor', defaultLabel: 'Exposed Floor', orientation: getOrientationSuffix(element, preferences, globalOrientationOffset) });
    }
    return format({ ruleId: 'externalWall', defaultLabel: 'Wall', orientation: getOrientationSuffix(element, preferences, globalOrientationOffset) });
  }

  if (
    element.type === 'BuildingElementPartyWall' ||
    element.type === 'BuildingElementAdjacentConditionedSpace' ||
    element.type === 'BuildingElementAdjacentUnconditionedSpace_Simple'
  ) {
    const partyAdjacentName = isVulcanUiPartyFloorElement(element);
    const isParty = element.type === 'BuildingElementPartyWall' || partyAdjacentName;
    const prefix = isParty
      ? 'Party'
      : element.type === 'BuildingElementAdjacentConditionedSpace'
        ? 'Internal'
        : 'Unheated';
    const surface = getAdjacentSurfaceName(element, elementsById);
    // Party walls (and party-toggled adjacent elements) sit between two heated
    // dwellings — they don't have a physically meaningful "compass orientation"
    // the way external walls do. Polyline winding can still produce an
    // orientation360, but propagating that into the name causes confusion when
    // the assessor's mental model of "which neighbour" doesn't line up with
    // the polyline's outward normal (in the party-wall winding regression, an
    // east-face wall was mislabelled "(W)" because it was drawn on the inside
    // of an L-plan return). Disambiguation for multiple party walls
    // falls back to numeric suffixes via `generateUniqueElementName`.
    const useOrientation = !isParty && surface.useOrientation;
    return format(
      {
        ruleId: adjacentNamingRuleForSurface(prefix, surface.suffix),
        defaultLabel: `${prefix} ${surface.suffix}`,
        orientation: useOrientation ? getOrientationSuffix(element, preferences, globalOrientationOffset) : '',
      }
    );
  }

  if (element.type === 'HotWaterDemand') {
    const sub = (element as HotWaterDemand).subcategory;
    if (sub === 'Bath') {
      return format({ ruleId: 'hotWaterDerived', defaultLabel: 'Bath', derivedLabel: 'Bath', derivedOptionId: sub });
    }
    if (sub === 'MixerShower' || sub === 'InstantElecShower') {
      return format({ ruleId: 'hotWaterDerived', defaultLabel: 'Shower', derivedLabel: 'Shower', derivedOptionId: sub });
    }
    if (sub === 'OtherWaterUseDetails') {
      return format({ ruleId: 'hotWaterDerived', defaultLabel: 'Tap', derivedLabel: 'Tap', derivedOptionId: sub });
    }
  }

  if (element.type === 'Appliance') {
    const key = (element as Appliance).appliancekey;
    if (typeof key === 'string' && key.trim()) {
      const label = normalizeAutoNameTypeToken(key);
      if (label) {
        return format({ ruleId: 'applianceDerived', defaultLabel: label, derivedLabel: label, derivedOptionId: key });
      }
    }
  }

  if (element.type === 'ThermalBridgeLinear' || element.type === 'ThermalBridgePoint') {
    const ex = element.extra_json;
    if (ex && typeof ex === 'object' && !Array.isArray(ex)) {
      const jt = (ex as Record<string, unknown>).junction_type;
      if (typeof jt === 'string' && jt.trim()) {
        return format({ ruleId: 'thermalBridge', defaultLabel: 'TB', detail: jt.trim() });
      }
    }
  }

  if (element.type === 'BuildingElementTransparent') {
    return format({ ruleId: 'window', defaultLabel: getElementTypeBaseName(element.type) });
  }

  const fallbackRule = element.type ? fallbackNamingRuleForElementType(element.type) : null;
  const fallbackLabel = element.type ? getElementTypeBaseName(element.type) : 'Element';
  if (fallbackRule) {
    return format({ ruleId: fallbackRule, defaultLabel: fallbackLabel });
  }
  return number ? `${fallbackLabel} ${number}` : fallbackLabel;
};

