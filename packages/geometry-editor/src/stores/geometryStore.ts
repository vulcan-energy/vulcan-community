const isNameAutoSyncEnabled = (
  element: Element,
  elementsById: Record<string, Element>,
  floors?: Floor[],
  currentNamingPreferences: NamingPreferences = DEFAULT_NAMING_PREFERENCES_FOR_AUTO_SYNC,
  globalOrientationOffset = 0,
  previousNamingPreferences?: NamingPreferences,
): boolean => {
  if (element._nameAutoSync === true) return true;
  if (element._nameAutoSync === false) return false;
  if (isNameAutoGeneratedWithOrientationLabelVariants(element, elementsById, floors, currentNamingPreferences, undefined, globalOrientationOffset)) return true;
  if (
    previousNamingPreferences &&
    previousNamingPreferences !== currentNamingPreferences &&
    isNameAutoGeneratedWithOrientationLabelVariants(element, elementsById, floors, previousNamingPreferences, undefined, globalOrientationOffset)
  ) return true;
  if (isNameAutoGeneratedWithOrientationLabelVariants(element, elementsById, floors, DEFAULT_NAMING_PREFERENCES_FOR_AUTO_SYNC, undefined, globalOrientationOffset)) {
    return true;
  }
  if (isNameAutoGeneratedWithLegacyFloorLabels(element, elementsById, floors, currentNamingPreferences, currentNamingPreferences, globalOrientationOffset)) return true;
  if (
    previousNamingPreferences &&
    previousNamingPreferences !== currentNamingPreferences &&
    isNameAutoGeneratedWithLegacyFloorLabels(element, elementsById, floors, previousNamingPreferences, currentNamingPreferences, globalOrientationOffset)
  ) return true;
  if (isNameAutoGeneratedWithLegacyFloorLabels(element, elementsById, floors, DEFAULT_NAMING_PREFERENCES_FOR_AUTO_SYNC, currentNamingPreferences, globalOrientationOffset)) {
    return true;
  }
  const legacyBaseName = getElementTypeBaseName(element.type);
  if (legacyBaseName && looksLikeAutoGeneratedName(element.name, legacyBaseName)) return true;
  return false;
};

// Decide the name + auto-sync flag for a duplicated element. When the source is
// auto-synced we regenerate through the auto-naming path (canonical name, scoped
// uniqueness) and mark the copy explicitly auto; otherwise we keep a manual copy
// derived from the source name. Pass an `elementsById` that already includes any
// previously-allocated duplicates so sibling auto-names don't collide.
const computeDuplicateName = (
  src: Element,
  elementsById: Record<string, Element>,
  floors: Floor[] | undefined,
  takenNames: string[],
  preferences: NamingPreferences,
  globalOrientationOffset: number,
): { name: string; nameAutoSync: boolean } => {
  if (isNameAutoSyncEnabled(src, elementsById, floors, preferences, globalOrientationOffset)) {
    return {
      name: generateDefaultElementName(src, elementsById, undefined, floors, preferences, undefined, globalOrientationOffset),
      nameAutoSync: true,
    };
  }
  const baseName = (src.name || '').replace(/_\d+$/, '');
  return { name: generateUniqueElementName(baseName, takenNames), nameAutoSync: false };
};

