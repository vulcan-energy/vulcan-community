type GeometryStoreDropProbe = {
  active?: boolean;
  storeWrites?: Record<string, number>;
  storeDurationsMs?: Record<string, number>;
  storeActionSamples?: Array<{ name: string; durationMs: number }>;
};

function activeGeometryStoreDropProbe(): GeometryStoreDropProbe | null {
  if (typeof window === 'undefined') return null;
  const probe = (window as unknown as { __vulcanGeometryDropProbe?: GeometryStoreDropProbe })
    .__vulcanGeometryDropProbe;
  return probe?.active ? probe : null;
}

function recordGeometryStoreWrite(actionName: string): void {
  geometryPerf.record(`GeometryStore.${actionName}.write`, 0);
  const probe = activeGeometryStoreDropProbe();
  if (!probe) return;
  probe.storeWrites ??= {};
  probe.storeWrites[actionName] = (probe.storeWrites[actionName] ?? 0) + 1;
}

function measureGeometryStoreAction<T>(actionName: string, fn: () => T): T {
  const probe = activeGeometryStoreDropProbe();
  const startedAt = probe ? performance.now() : 0;
  try {
    return geometryPerf.measure(`GeometryStore.${actionName}.total`, fn);
  } finally {
    if (probe) {
      const durationMs = performance.now() - startedAt;
      probe.storeDurationsMs ??= {};
      probe.storeDurationsMs[actionName] = (probe.storeDurationsMs[actionName] ?? 0) + durationMs;
      probe.storeActionSamples ??= [];
      probe.storeActionSamples.push({
        name: actionName,
        durationMs: Number(durationMs.toFixed(2)),
      });
    }
  }
}

