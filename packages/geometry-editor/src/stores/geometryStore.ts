const coordinatesChanged = (
  oldCoords: ElementCoordinate[] | undefined,
  newCoords: ElementCoordinate[] | undefined,
): boolean => {
  if (!newCoords) return false;
  if (!oldCoords || oldCoords.length !== newCoords.length) return true;
  for (let i = 0; i < newCoords.length; i++) {
    const a = oldCoords[i];
    const b = newCoords[i];
    if (!a || !b) return true;
    if (Math.abs(a.x - b.x) > 1e-9 || Math.abs(a.y - b.y) > 1e-9 || Math.abs(a.z - b.z) > 1e-9) {
      return true;
    }
  }
  return false;
};

