export interface CreateGeometryStoreOptions {
  /**
   * Host-owned path used for new/reset documents and legacy CSVs without a
   * DefaultsPath row. `undefined` preserves the host's historic path; `null`
   * means the host has no implicit workspace defaults resource.
   */
  defaultDefaultsPath?: string | null;
  initialNamingPreferences?: NamingPreferences;
  modelSchemaProfilePort?: GeometryModelSchemaProfilePort;
  schemaPort?: GeometrySchemaPort;
  workspaceResourcePort?: GeometryWorkspaceResourcePort;
  /** Exact metadata row keys interpreted by a private host and preserved by this store. */
  hostDocumentMetadataKeys?: readonly string[];
}

const resolveDefaultDefaultsPath = (
  configuredPath: CreateGeometryStoreOptions['defaultDefaultsPath'],
): string | undefined => {
  if (configuredPath === undefined) return DEFAULT_DEFAULTS_PATH;
  if (configuredPath === null) return undefined;
  const trimmed = configuredPath.trim();
  if (!trimmed) {
    throw new Error('defaultDefaultsPath must be a non-empty path or null');
  }
  return trimmed;
};

const resolveHostDocumentMetadataKeys = (
  configuredKeys: CreateGeometryStoreOptions['hostDocumentMetadataKeys'],
): readonly string[] => Object.freeze(
  [...new Set((configuredKeys ?? []).map((key) => key.trim()))].map((key) => {
    if (!key || key.includes(',')) {
      throw new Error('hostDocumentMetadataKeys must contain non-empty CSV-safe row names');
    }
    return key;
  }),
);

const freezePostCommandEvent = (
  event: GeometryPostCommandEvent,
): GeometryPostCommandEvent => Object.freeze({
  ...event,
  remaps: Object.freeze(event.remaps.map((remap) => Object.freeze({ ...remap }))),
});

const withPrecomputedDefaultsLookup = (
  state: GeometryState,
  update: unknown,
): Partial<GeometryState> | GeometryState => {
  if (
    update &&
    typeof update === 'object' &&
    Object.prototype.hasOwnProperty.call(update, 'defaultsJson')
  ) {
    const defaultsJson = (update as Partial<GeometryState>).defaultsJson;
    if (defaultsJson !== state.defaultsJson) {
      return {
        ...update,
        defaultsLookup: createDefaultsLookup(defaultsJson),
      } as Partial<GeometryState>;
    }
  }
  return update as Partial<GeometryState> | GeometryState;
};

