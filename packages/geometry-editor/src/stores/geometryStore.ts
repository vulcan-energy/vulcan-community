const formatLegacyGfF1FloorLabel = (storeyIndex: number | undefined): string => {
  if (typeof storeyIndex !== 'number' || !Number.isFinite(storeyIndex)) return '';
  const storey = Math.floor(storeyIndex);
  if (storey < 0) return `B${Math.abs(storey)}`;
  return storey === 0 ? 'GF' : `F${storey}`;
};

