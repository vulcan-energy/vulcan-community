const adjacentNamingRuleForSurface = (
  prefix: 'Internal' | 'Party' | 'Unheated',
  suffix: string,
): NamingRuleId => {
  const surface = suffix === 'Floor' || suffix === 'Ceiling' ? suffix : 'Wall';
  if (prefix === 'Party') {
    if (surface === 'Floor') return 'partyFloor';
    if (surface === 'Ceiling') return 'partyCeiling';
    return 'partyWall';
  }
  if (prefix === 'Unheated') {
    if (surface === 'Floor') return 'unheatedFloor';
    if (surface === 'Ceiling') return 'unheatedCeiling';
    return 'unheatedWall';
  }
  if (surface === 'Floor') return 'internalFloor';
  if (surface === 'Ceiling') return 'internalCeiling';
  return 'internalWall';
};

